import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const snapshotPath = resolve(root, "linked-formatting-keys.json");
const generatedPath = resolve(root, "src/storyforgeLinkedFormattingKeys.generated.ts");

const snapshot = JSON.parse(readFileSync(snapshotPath, "utf8"));
if (
	typeof snapshot.contractVersion !== "number" ||
	!Array.isArray(snapshot.keys) ||
	snapshot.valueTypes == null ||
	typeof snapshot.valueTypes !== "object"
) {
	throw new Error("linked-formatting-keys.json is malformed");
}
if (new Set(snapshot.keys).size !== snapshot.keys.length) {
	throw new Error("Linked key snapshot contains duplicates");
}
for (const key of snapshot.keys) {
	if (typeof snapshot.valueTypes[key] !== "string") {
		throw new Error(`valueTypes missing ${key}`);
	}
}

const expected = buildGenerated(snapshot.contractVersion, snapshot.keys, snapshot.valueTypes);
if (readFileSync(generatedPath, "utf8") !== expected) {
	throw new Error(
		"src/storyforgeLinkedFormattingKeys.generated.ts is stale; run storyForge npm run sync:formatting-contract",
	);
}
console.log(`Verified ${snapshot.keys.length} shared linked formatting keys.`);

function buildGenerated(contractVersion, keyList, types) {
	const valueTypeLines = keyList.map((key) => `\t${key}: ${types[key]};`).join("\n");
	return `/**
 * GENERATED by storyForge/sync-formatting-contract.mjs.
 * Source of truth: storyForge/src/hostApi.ts LINKED_FORMATTING_KEYS.
 * Do not edit this file by hand.
 */
export const STORYFORGE_FORMATTING_CONTRACT_VERSION = ${contractVersion} as const;

export const LINKED_FORMATTING_KEYS = ${JSON.stringify(keyList, null, "\t")} as const;

export type SfLinkedFormattingKey = (typeof LINKED_FORMATTING_KEYS)[number];

export type LinkedFormattingValues = {
${valueTypeLines}
};
`;
}
